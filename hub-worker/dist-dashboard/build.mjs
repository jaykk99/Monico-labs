/* Builds the single-file Worker for the Cloudflare dashboard paste flow
 * (no wrangler needed). Run: node hub-worker/dist-dashboard/build.mjs */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, copyFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = join(mkdtempSync(join(tmpdir(), "monico-hub-")), "worker.js");
const bin = process.env.ESBUILD ? [process.env.ESBUILD, []] : ["npx", ["-y", "esbuild@0.25"]];
execFileSync(bin[0], [...bin[1], "src/worker.js", "--bundle", "--format=esm",
  "--platform=neutral", "--target=es2022", `--outfile=${raw}`], { cwd: root, stdio: "inherit" });

const header =
  "/* Monico Labs hub - single-file Worker for Cloudflare dashboard paste.\n" +
  " * Generated by dist-dashboard/build.mjs from hub-worker/src (edit src, then rebuild).\n" +
  " * Needs: D1 bound as DB; secrets HUB_SIGNING_KEY, OWNER_TOTP_SECRET, OWNER_RECOVERY_HASH. */\n";
writeFileSync(join(root, "dist-dashboard", "worker.js"), header + readFileSync(raw, "utf-8"));
copyFileSync(join(root, "migrations", "0001_init.sql"), join(root, "dist-dashboard", "migration.sql"));
console.log("wrote dist-dashboard/worker.js and dist-dashboard/migration.sql");
